export function worldName(id: WorldId, lang: Language): string {
  return lang === "en"
    ? { gemland: "Gemland", moonland: "Moonland", aztecland: "Aztecland" }[id]
    : {
        gemland: "Terre des gemmes",
        moonland: "Terre lunaire",
        aztecland: "Terre aztèque",
      }[id];
}
