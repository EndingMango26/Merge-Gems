import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, relative, sep } from 'node:path';

// GitHub project Pages serves this app below the repository name.
const base = '/Merge-Gems/';
const output = resolve('dist');
async function filesIn(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(entry => {
    const name = resolve(directory, entry.name);
    return entry.isDirectory() ? filesIn(name) : [name];
  }));
  return nested.flat();
}

const files = (await filesIn(output)).filter(file => relative(output, file) !== 'sw.js').sort();
if (!files.some(file => relative(output, file) === 'index.html')) {
  throw new Error('Build the app before generating the offline worker (dist/index.html is missing).');
}
const digest = createHash('sha256');
const urls = [];
for (const file of files) {
  const name = relative(output, file).split(sep).join('/');
  digest.update(name).update('\0').update(await readFile(file)).update('\0');
  urls.push(base + name);
}
const version = digest.digest('hex').slice(0, 20);
const source = `/* Generated by scripts/build-sw.mjs. Do not edit dist/sw.js. */
const VERSION = ${JSON.stringify(version)};
const CACHE = 'merge-gems-assets-' + VERSION;
const BASE = ${JSON.stringify(base)};
const FILES = ${JSON.stringify(urls)};

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    try {
      const cache = await caches.open(CACHE);
      await cache.addAll(FILES);
    } catch (error) {
      await caches.delete(CACHE);
      throw error;
    }
    // A replacement waits until the user accepts the update or closes old tabs.
  })());
});

self.addEventListener('activate', event => {
  // Keep previous asset caches: an already-open older tab may still need its files.
  // Game saves live in localStorage and are never read or deleted by this worker.
  event.waitUntil(self.clients.claim());
});

self.addEventListener('message', event => {
  if (event.data?.type === 'SKIP_WAITING') event.waitUntil(self.skipWaiting());
  if (event.data?.type === 'GET_VERSION') {
    const target = event.ports[0] || event.source;
    target?.postMessage({ type: 'VERSION', version: VERSION });
  }
});

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    if (request.mode === 'navigate') {
      // Serve one consistent app version; the browser checks sw.js for updates.
      const shell = await cache.match(BASE + 'index.html');
      if (shell) return shell;
    }
    const saved = await cache.match(request, { ignoreSearch: true });
    if (saved) return saved;
    // Keep old hashed files available to tabs using the preceding app version.
    const previous = await caches.match(request, { ignoreSearch: true });
    if (previous) return previous;
    return fetch(request);
  })());
});
`;
await writeFile(resolve(output, 'sw.js'), source);
console.log(`Offline cache ${version}: ${urls.length} bundled files, scope ${base}`);
